/** Layout yarcoclipz : facecam en haut (1080x560), titre au milieu,
 * gameplay en bas (1080x1060, fenetre y 700-1599 : visage au jet +
 * sous-titres brules visibles). Zoom punch + shake sur le jet
 * (punchFrame, local au segment), centre sur le haut du plan (visage). */
const Yarcoclipz: React.FC<{ startFrom: number; showTitle: boolean; punchFrame: number }> = ({ startFrom, showTitle, punchFrame }) => {
  const frame = useCurrentFrame();
  // Facecam : region source (0, 0, 916, 530) -> 1080x560 (scale 1,179,
  //   fenetre y 0-475 : visage entier).
  // Gameplay : region source y 700-1599 -> 1080x1060 (scale 1,179 ;
  //   video 1080x1919 decalée de -825).
  let scale = 1;
  let tx = 0;
  let ty = 0;
  if (punchFrame >= 0 && frame >= punchFrame - 4 && frame <= punchFrame + 10) {
    const bump = Math.sin((Math.PI * (frame - (punchFrame - 4))) / 14);
    scale = 1 + 0.09 * Math.max(0, bump);
  }
  if (punchFrame >= 0 && frame >= punchFrame - 2 && frame <= punchFrame + 10) {
    tx += (hash01(frame) - 0.5) * 12;
    ty += (hash01(frame + 13) - 0.5) * 10;
  }
  return (
    <AbsoluteFill style={{ backgroundColor: '#000' }}>
      {/* Facecam en haut */}
      <div style={{ position: 'absolute', top: 0, left: 0, width: 1080, height: 560, overflow: 'hidden' }}>
        <OffthreadVideo src={SF('source-30fps.mp4')} startFrom={startFrom} muted style={{ position: 'absolute', left: 0, top: 0, width: 1080, height: 1919 }} />
      </div>
      {showTitle ? <TitleBand /> : null}
      {/* Gameplay en bas, avec zoom punch + shake */}
      <div style={{ position: 'absolute', top: 860, left: 0, width: 1080, height: 1060, overflow: 'hidden' }}>
        <div style={{ position: 'absolute', inset: 0, transform: `scale(${scale.toFixed(3)}) translate(${tx.toFixed(1)}px, ${ty.toFixed(1)}px)`, transformOrigin: '50% 30%' }}>
          <OffthreadVideo src={SF('source-30fps.mp4')} startFrom={startFrom} muted style={{ position: 'absolute', left: 0, top: -825, width: 1080, height: 1919 }} />
        </div>
      </div>
    </AbsoluteFill>
  );
};

